async def seed() -> None:
    settings = get_settings()
    pool = await create_db_pool(settings)
    embedding_client = LLMFactory.build_embedding_client(settings)
    vector_store = PGVectorStore(pool)

    print(f"Seeding {len(FAQ_DOCUMENTS)} wedding dress FAQ documents...")
    documents = [
        Document(
            doc_id=str(uuid.uuid5(uuid.NAMESPACE_DNS, f"wedding_faq_{d['title']}")),
            content=d["content"],
            metadata={"title": d["title"], "category": "wedding_dress_faq"},
        )
        for d in FAQ_DOCUMENTS
    ]

    texts = [doc.content for doc in documents]
    print("Generating embeddings (this may take a moment)...")
    try:
        embeddings = await embedding_client.aembed_documents(texts)
    except Exception as e:
        msg = str(e)
        print(f"\n⚠️  Embedding API error: {msg}")
        if "insufficient balance" in msg or "1008" in msg:
            print("   MiniMax Embedding 账户余额不足，请充值后重新运行 seed_faq.py")
            print("   充值地址：https://platform.minimaxi.com/")
        elif "No embedding data" in msg or "no vectors" in msg.lower():
            print("   提示：请确认 EMBEDDING_MODEL 配置正确（MiniMax 使用 embo-01）")
        print("\n   系统仍可运行——订单查询/HITL 功能不受影响")
        print("   只有 FAQ 知识库（婚纱面料、款式等咨询）暂不可用")
        await pool.close()
        return

    await vector_store.upsert(documents, embeddings)
    print(f"✓ Seeded {len(documents)} FAQ documents.")
    await pool.close()


if __name__ == "__main__":
    asyncio.run(seed())
